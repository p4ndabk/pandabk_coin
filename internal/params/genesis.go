package params

// GenesisSpec descreve o bloco 0 de um perfil. O gênesis é minerado uma única
// vez offline (comando dev `zhu genesis`, M2) e hardcoded aqui; a chain o
// valida por igualdade exata de hash, e o hash serve de ID da rede no
// handshake P2P.
type GenesisSpec struct {
	Timestamp int64
	Message   string
	Bits      uint32
	Nonce     uint64
	Hash      [32]byte
}

